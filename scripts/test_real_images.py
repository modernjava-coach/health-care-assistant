def main():
    """Run all tests"""
    print("\n" + "=" * 80)
    print("FASTAPI ENDPOINT TESTING WITH REAL MEDICAL NOTE IMAGES")
    print("=" * 80)
    
    results = []
    ocr_results = {}
    
    # Run all tests
    result1 = test_soap_generation_with_sample_note()
    results.append(("SOAP with sample_note.png", result1[0]))
    ocr_results["sample_note"] = result1[1]
    
    result2 = test_soap_generation_with_realistic_note()
    results.append(("SOAP with realistic_note.png", result2[0]))
    ocr_results["realistic_note"] = result2[1]
    
    results.append(("Medical Codes with sample_note.png", test_medical_codes_with_sample_note()))
    results.append(("Medical Codes with realistic_note.png", test_medical_codes_with_realistic_note()))
    
    # Print summary
    print("\n" + "="*80)
    print("TEST SUMMARY")
    print("="*80)
    
    passed = sum(1 for _, result in results if result)
    total = len(results)
    
    for test_name, result in results:
        status = "[PASS]" if result else "[FAIL]"
        print(f"{status}: {test_name}")
    
    print(f"\nTotal: {passed}/{total} tests passed")
    
    if passed == total:
        print("\nAll tests passed successfully!")
        return 0
    else:
        print(f"\nWarning: {total - passed} test(s) failed")
        return 1


if __name__ == "__main__":
    exit(main())
